#!/usr/bin/env node
import fs from 'node:fs/promises';
import path from 'node:path';
import { validateBrowserJourney } from './validate-browser-journey.mjs';
import { validateBrowserReport } from './validate-browser-report.mjs';
import { resolveOwnedSession, writeFileAtomic } from './run-browser-ingestion-verification.mjs';
import { isEntrypoint } from './reporting.mjs';

export async function appendEvidence(session, fragment) {
    const paths = await resolveOwnedSession(session);
    if (!paths) throw new Error('只能修改本工具创建的会话');
    if (!fragment || Object.keys(fragment).some(k => !['step', 'results', 'triggerWindow', 'accountConditions'].includes(k)) || !fragment.step) throw new Error('证据输入需要 step，可选 results、triggerWindow、accountConditions');
    const original = await fs.readFile(paths.bundle, 'utf8');
    const bundle = JSON.parse(original);
    const journey = validateBrowserJourney(bundle.journey, bundle.contract);
    if (journey.status !== 'PASS') throw new Error(journey.issues.join('\n'));
    const report = bundle.browserReport;
    const next = { ...report, steps: [...report.steps, fragment.step], results: [...report.results, ...(fragment.results || [])] };
    for (const key of ['triggerWindow', 'accountConditions']) if (fragment[key] !== undefined) next[key] = fragment[key];
    const validation = validateBrowserReport(next, bundle.journey, bundle.contract, { partial: true });
    if (validation.status !== 'PASS') throw new Error(validation.issues.join('\n'));
    // Refuse concurrent edits; no evidence values are generated by this helper.
    if (await fs.readFile(paths.bundle, 'utf8') !== original) throw new Error('会话已修改，请重新读取后追加');
    await writeFileAtomic(paths.bundle, JSON.stringify({ ...bundle, browserReport: next }, null, 2) + '\n', paths.session);
    return { status: 'PASS', stepCount: next.steps.length };
}

if (isEntrypoint(import.meta.url)) {
    const args = process.argv.slice(2);
    if (args.length === 1 && args[0] === '--help') console.log('用法：--session <自有会话目录> --input <证据 JSON>。输入 step 及可选 results、triggerWindow、accountConditions；不生成时间、状态或匹配数。');
    else if (args.length !== 4 || args[0] !== '--session' || args[2] !== '--input') { console.error('需要 --session <目录> --input <文件>'); process.exitCode = 2; }
    else appendEvidence(path.resolve(args[1]), JSON.parse(await fs.readFile(args[3], 'utf8')))
        .then(() => console.log('证据已校验并追加'))
        .catch(error => { console.error(error.message); process.exitCode = 1; });
}
